#!/usr/bin/env python3
"""Generates app/qml/KeyCodes.js from linux/input-event-codes.h.

The app records shortcuts as Linux key codes (Qt's native scan code minus 8 on
XKB platforms) and stores them by name, exactly like the service expects.
"""
import re
import sys

header = sys.argv[1] if len(sys.argv) > 1 else "/usr/include/linux/input-event-codes.h"
out = sys.argv[2] if len(sys.argv) > 2 else "app/qml/KeyCodes.js"
codes = {}
for line in open(header):
    m = re.match(r"#define\s+(KEY_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)", line)
    if not m:
        continue
    name, value = m.group(1), int(m.group(2), 0)
    if name in ("KEY_MAX", "KEY_CNT", "KEY_RESERVED", "KEY_MIN_INTERESTING"):
        continue
    codes.setdefault(value, name)  # first name wins (aliases come later)
entries = ",\n".join(f'    {v}: "{n}"' for v, n in sorted(codes.items()))
open(out, "w").write(
    "// Generated by scripts/gen-keycodes.py from linux/input-event-codes.h. Do not edit.\n"
    ".pragma library\n\n"
    "var names = {\n" + entries + "\n};\n"
)
print(f"wrote {len(codes)} key names to {out}")
